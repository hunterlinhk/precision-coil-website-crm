// Pick the localized field from a row with _en/_zh columns, falling back to English.
export function L(row: any, field: string, locale: Locale): string {
  if (!row) return '';
  return (locale === 'zh' ? row[`${field}_zh`] : row[`${field}_en`]) || row[`${field}_en`] || '';
}
